"""Synthetic public fixtures: independent source groups, explicit reference labels.

These are contract tests, not representative studio footage or a powered study.
Labels are specified by construction, not generated by the component under test.
"""
from pathlib import Path
import json
from .core import digest

# Reviewed independently of the fixture directory. Altering labels or splits
# requires a new version and a new predeclared experiment, never another seed hunt.
FROZEN_SHA256 = '1b5d9932a204b9ca0bdc172e699118ffad0506a949251f2abda2ae41b58b041a'

CRITERIA = {'version': 'caption-rubric-1', 'max_bytes': 65536, 'duration_seconds': 15,
            'definition': 'UTF-8 SRT; optional BOM/CRLF; sequential IDs; nonempty text; finite increasing nonoverlapping cue times within 15s.',
            'min_quality_gain': 0.05, 'max_quality_loss': 0.0, 'min_cost_reduction': 0.20}


def create(root):
    root = Path(root)
    root.mkdir(parents=True, exist_ok=False)
    tasks, labels = [], {}
    for group in range(12):
        split = 'dev' if group < 8 else 'holdout'
        # Text and timings differ by source group; paired variants stay together.
        start = 100 + group*61
        def stamp(ms): return f'00:00:{ms//1000:02},{ms%1000:03}'
        def cue(n, a, b, text): return f'{n}\n{stamp(a)} --> {stamp(b)}\n{text}'
        a = cue(1, start, start+1200, f'Source {group}: café & motion')
        b = cue(2, start+1600, start+2600, f'Frame {group*17+11}')
        cases = [
            ('valid', (a+'\n\n'+b+'\n').encode(), True),
            ('bom-crlf', ('\ufeff'+a+'\n\n'+b).replace('\n', '\r\n').encode(), True),
            ('overlap', (a+'\n\n'+cue(2, start+900, start+2000, 'overlap')).encode(), False),
            ('backward', cue(1, start+1200, start, 'backward').encode(), False),
            ('past-end', cue(1, 14000, 17000+group, 'past media end').encode(), False),
            ('duplicate-id', (a+'\n\n'+cue(1, start+1600, start+2600, 'duplicate')).encode(), False),
        ]
        for family, data, valid in cases:
            name = f'{split}-{group:02}-{family}'
            rel = f'inputs/{name}.srt'
            path = root / rel
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(data)
            tasks.append(dict(task_id=name, task_type='caption-validation', input_ref=rel,
                              input_hash=__import__('hashlib').sha256(data).hexdigest(),
                              source_group=f'generated-source-{group:02}', family=family,
                              success_criteria_version=CRITERIA['version'], permissions=['read-fixture', 'run-ffprobe'],
                              resource_budget={'wall_seconds': 3, 'input_bytes': 65536, 'concurrency': 1},
                              split_id=split, created_at='2026-11-21T00:00:00Z'))
            labels[name] = {'valid': valid, 'label_source': 'fixture-construction-v1', 'family': family}
    manifest = dict(version='caption-fixtures-1', seed=20261120, tasks=tasks, criteria=dict(CRITERIA),
                    labels=labels, limitation='12 synthetic source groups, 6 related variants each; not 72 independent real-world samples.')
    (root / 'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    (root / 'manifest.sha256').write_text(digest(manifest)+'\n', encoding='ascii')
    return manifest


def load(root, expected_hash):
    root = Path(root)
    m = json.loads((root/'manifest.json').read_text(encoding='utf-8'))
    if digest(m) != expected_hash: raise ValueError('frozen manifest changed')
    dev = {t['source_group'] for t in m['tasks'] if t['split_id'] == 'dev'}
    hold = {t['source_group'] for t in m['tasks'] if t['split_id'] == 'holdout'}
    if dev & hold: raise ValueError('source group leakage')
    hashes = [t['input_hash'] for t in m['tasks']]
    if len(hashes) != len(set(hashes)): raise ValueError('duplicate content leakage')
    for task in m['tasks']:
        p = (root / task['input_ref']).resolve()
        if not p.is_relative_to(root.resolve()): raise ValueError('fixture path escape')
        if __import__('hashlib').sha256(p.read_bytes()).hexdigest() != task['input_hash']:
            raise ValueError('frozen input changed')
    return m


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    created = create(args.out)
    if digest(created) != FROZEN_SHA256: raise ValueError('generator differs from reviewed frozen dataset')
