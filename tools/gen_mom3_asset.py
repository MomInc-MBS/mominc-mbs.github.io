"""Regenerate apps/alarm/ui/mom3.webp + mom3-manifest.js from Ian's three-head art.
Source: D:/MOM Rig/ai-visualizer/assets/mom3.png (read-only). Run: python tools/gen_mom3_asset.py [source.png]"""
import json, sys, pathlib
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else 'D:/MOM Rig/ai-visualizer/assets/mom3.png'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'apps/alarm/ui'
W = 640
im = Image.open(SRC).convert('RGB')
sw, sh = im.size
# content bounds in source px: whole width, head-top (below the rain) to the fade of the chest
cb = dict(x=0, y=80, w=sw, h=1170)
# combined eye band (all three heads' eyes + glasses) in source px, measured on the art
eye = dict(y0=240, y1=452)
# mouth anchors: normalized to the SOURCE image (ported from faces/mom3/index.html MOUTHS)
mouths = {
  'center': dict(box=[0.460, 0.305, 0.097, 0.038], lip=0.330, jaw=0.382, region=[0.410, 0.610], maxDrop=4),
  'left':   dict(box=[0.062, 0.337, 0.046, 0.034], lip=0.3545, jaw=0.399, region=[0.052, 0.170], maxDrop=3),
  'right':  dict(box=[0.896, 0.338, 0.042, 0.034], lip=0.3545, jaw=0.399, region=[0.830, 0.948], maxDrop=3),
}
crop = im.crop((cb['x'], cb['y'], cb['x'] + cb['w'], cb['y'] + cb['h']))
crop = crop.resize((W, round(W * cb['h'] / cb['w'])), Image.LANCZOS)
crop.save(OUT / 'mom3.webp', quality=72, method=6)
man = dict(source=dict(w=sw, h=sh), content=cb, eye=eye, mouths=mouths, asset=dict(file='mom3.webp', w=crop.width, h=crop.height))
(OUT / 'mom3-manifest.js').write_text('// generated by tools/gen_mom3_asset.py - do not edit\nexport const MANIFEST = ' + json.dumps(man, indent=1) + ';\n')
print(crop.size, (OUT / 'mom3.webp').stat().st_size, 'bytes')
